# Madlibs Game
# Word Game where you create Story
# by filling in blanks with random words

adjective = input("Enter an adjective (Description): ")
place = input("Enter a place: ")
animal = input("Enter an animal: ")
verb = input("Enter a verb ending with 'ing': ")
food = input("Enter a food: ")

print(f"Yesterday I visited a {adjective} {place}.")
print(f"Suddenly, a giant {animal} came {verb} towards me.")
print(f"Everyone started screaming and running away.")
print(f"But the {animal} only wanted my {food}.")
print(f"I shared my {food}, and we became best friends!")
print("It was the funniest day of my life!")


